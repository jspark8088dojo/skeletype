// Builds src/copy.js from the content workflow's output.
//
// Usage: node tools/make-copy.mjs <journal.jsonl | results.json> <out.js>
//   journal.jsonl  the workflow journal (uses the verified content when present, else the draft)
//   results.json   the workflow's final return value: [{ id, draft, verified: { content, changes } }]
import { readFileSync, writeFileSync } from 'node:fs';

const [src, out] = process.argv.slice(2);
if (!src || !out) {
  console.error('usage: node tools/make-copy.mjs <journal.jsonl|results.json> <out.js>');
  process.exit(1);
}

// Extra answers accepted in free recall on top of what the content pass produced.
const EXTRA_ALIASES = {
  prox: { en: ['proximal phalanx'], fr: ['phalange proximale'] },
  mid: { en: ['middle phalanx', 'intermediate phalanges', 'intermediate phalanx'], fr: ['phalange moyenne', 'phalanges intermédiaires', 'phalange intermédiaire'] },
  dist: { en: ['distal phalanx'], fr: ['phalange distale'] },
};

const byTask = {};
if (src.endsWith('.jsonl')) {
  const labelOf = {};
  for (const line of readFileSync(src, 'utf8').split('\n')) {
    if (!line.trim()) continue;
    const e = JSON.parse(line);
    if (e.type === 'started') labelOf[e.agentId] = e.label;
    if (e.type === 'result' && e.result && labelOf[e.agentId]) {
      const [stage, id] = labelOf[e.agentId].split(':');
      byTask[id] ||= {};
      byTask[id][stage] = stage === 'verify' ? e.result.content : e.result;
    }
  }
} else {
  for (const r of JSON.parse(readFileSync(src, 'utf8'))) byTask[r.id] = { draft: r.draft, verify: r.verified?.content };
}

// Only used while the content pass is still running (--placeholders): obviously temporary text.
const PLACEHOLDER = {
  L3: {
    items: [
      ['prox', 'proximal phalanges', 'phalanges proximales'],
      ['mid', 'middle phalanges', 'phalanges moyennes'],
      ['dist', 'distal phalanges', 'phalanges distales'],
      ['hallux', 'hallux', 'hallux'],
    ].map(([key, en, fr]) => ({ key, en, fr, enAliases: [], frAliases: [], frNote: '', latin: '', describe: '(placeholder)', cue: '(placeholder cue)', card: '(placeholder)', fact: '(placeholder)' })),
    examAngle: [],
    headline: '(placeholder headline)',
  },
};
const allowPlaceholders = process.argv.includes('--placeholders');

const pick = (id) => {
  const t = byTask[id];
  if (!t && allowPlaceholders && PLACEHOLDER[id]) { console.log(`${id}: PLACEHOLDER`); return PLACEHOLDER[id]; }
  if (!t) throw new Error(`no content for ${id}`);
  const used = t.verify ? 'verified' : 'draft';
  console.log(`${id}: ${used}`);
  return t.verify || t.draft;
};

const items = {};
const levels = {};
for (const id of ['L1', 'L2', 'L3']) {
  const c = pick(id);
  for (const it of c.items) {
    const extra = EXTRA_ALIASES[it.key] || {};
    const uniq = (list) => [...new Set(list.map((s) => s.trim().toLowerCase()).filter(Boolean))];
    // Drop the canonical name itself and any alias that only extends another accepted answer
    // ("first metatarsal bone", "1st metatarsal bone"): the app accepts an answer the moment it's typed,
    // so the longer form could never be completed.
    const aliasesFor = (canonical, list) => {
      const all = uniq([canonical, ...list]);
      return all.filter((a) => a !== canonical && !all.some((b) => b !== a && a.startsWith(`${b} `)));
    };
    const en = it.en.trim().toLowerCase();
    const fr = it.fr.trim().toLowerCase();
    items[it.key] = {
      en,
      enAliases: aliasesFor(en, [...(it.enAliases || []), ...(extra.en || [])]),
      fr,
      frAliases: aliasesFor(fr, [...(it.frAliases || []), ...(extra.fr || [])]),
      frNote: (it.frNote || '').trim(),
      latin: it.latin,
      describe: it.describe,
      cue: it.cue,
      card: it.card,
      fact: it.fact,
    };
  }
  levels[id] = { examAngle: c.examAngle, headline: c.headline };
}
const meshes = {};
for (const m of pick('MAP').meshes) meshes[m.key] = { en: m.en, fr: m.fr, describe: m.describe };

const body = JSON.stringify({ items, levels, meshes }, null, 2);
writeFileSync(out, `// Generated by tools/make-copy.mjs from the fact-checked content pass. Edit the wording here.\n\nexport default ${body};\n`);
console.log(`wrote ${out}: ${Object.keys(items).length} items, ${Object.keys(levels).length} levels, ${Object.keys(meshes).length} meshes`);
